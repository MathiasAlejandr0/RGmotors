for (const [plate, spec] of Object.entries(VEHICLE_SPECS)) {
  const allPhotos = map[plate] || [];
  const frontImg = `/cars/real_stock/${spec.frontPhoto}`;
  
  // Ensure front photo is first, followed by all other authentic photos for that plate
  const gallery = [
    frontImg,
    ...allPhotos
      .filter((f) => f !== spec.frontPhoto)
      .map((f) => `/cars/real_stock/${f}`)
  ];

  vehiclesList.push({
    slug: spec.slug,
    brand: spec.brand,
    model: spec.model,
    version: spec.version,
    year: spec.year,
    price: spec.price,
    km: spec.km,
    fuel: spec.fuel,
    transmission: spec.transmission,
    bodyType: spec.bodyType,
    location: spec.location,
    image: frontImg,
    gallery: gallery,
    engine: spec.engine,
    power: spec.power,
    traction: spec.traction,
    doors: spec.doors,
    owners: spec.owners,
    featured: spec.featured,
  });
}

// Write to data/vehicles.json
writeFileSync("data/vehicles.json", JSON.stringify(vehiclesList, null, 2), "utf8");
